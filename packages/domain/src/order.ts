import { generateKeyBetween, generateNKeysBetween } from 'fractional-indexing';

/**
 * Fractional order keys for sibling sections (TECH-DESIGN §4.3). A key sorts between its
 * neighbours by plain string comparison (byte order, the "C" collation on `section.order_key`),
 * so inserting or moving a section rewrites only that section's key.
 */

/** A key after `before` and before `after`; null or undefined means the start or the end. */
export function keyBetween(before?: string | null, after?: string | null): string {
  return generateKeyBetween(before, after);
}

/** `n` keys in order between `before` and `after`, e.g. for pasting several sections at once. */
export function keysBetween(
  before: string | null | undefined,
  after: string | null | undefined,
  n: number,
): string[] {
  return generateNKeysBetween(before, after, n);
}

/**
 * The key for an item placed at `index` among `keys` (sorted, without the item itself): 0 puts it
 * first, `keys.length` last. To move an item, pass its siblings without it.
 */
export function keyAt(keys: readonly string[], index: number): string {
  if (!Number.isInteger(index) || index < 0 || index > keys.length) {
    throw new RangeError(`index ${index} is outside 0–${keys.length}`);
  }
  return generateKeyBetween(keys[index - 1], keys[index]);
}

/** Whether a string is a valid order key (generated by this module). */
export function isOrderKey(key: string): boolean {
  try {
    generateKeyBetween(key, null);
    return true;
  } catch {
    return false;
  }
}

/**
 * Sorts siblings by key, then by id. Two devices that insert at the same place while offline can
 * produce the same key; the id keeps the order the same on every device.
 */
export function compareOrder(
  a: { orderKey: string; id: string },
  b: { orderKey: string; id: string },
): number {
  return compareBytes(a.orderKey, b.orderKey) || compareBytes(a.id, b.id);
}

// Keys and ids are ASCII, so UTF-16 code unit order is byte order. localeCompare would not be.
function compareBytes(a: string, b: string): number {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}
